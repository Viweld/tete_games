import 'package:core_ui/core_ui.dart';

class AppDatePickerTheme {
  final Color backgroundColor;
  final Color selectedDayBackgroundColor;
  final Color currentDayBackgroundColor;
  final Color iconColor;
  final Color dayTextColor;
  final Color disabledDayTextColor;
  final Color selectedDayTextColor;

  const AppDatePickerTheme({
    required this.backgroundColor,
    required this.selectedDayBackgroundColor,
    required this.currentDayBackgroundColor,
    required this.iconColor,
    required this.dayTextColor,
    required this.disabledDayTextColor,
    required this.selectedDayTextColor,
  });
}
