import 'package:core_ui/core_ui.dart';

final class AppTextTheme {
  final Color main;
  final Color secondary;
  final Color accent;
  final Color disabled;
  final Color success;
  final Color error;
  final Color white;

  const AppTextTheme({
    required this.main,
    required this.secondary,
    required this.accent,
    required this.disabled,
    required this.success,
    required this.error,
    required this.white,
  });
}
